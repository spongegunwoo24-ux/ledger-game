// Collects every non-ASCII character used in src/ so the web fonts can preload
// exactly the unicode-range slices the game needs (Korean fonts are split into ~100 slices).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../src', import.meta.url).pathname;
const chars = new Set();
function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name !== 'generated') walk(p);
    } else if (p.endsWith('.ts')) {
      for (const ch of readFileSync(p, 'utf8')) if (ch.charCodeAt(0) > 127) chars.add(ch);
    }
  }
}
walk(root);
const list = [...chars].sort().join('');
writeFileSync(
  join(root, 'generated/glyphs.ts'),
  `// Generated by scripts/glyphs.mjs — do not edit.\nexport const GLYPHS = ${JSON.stringify(list)};\n`,
);
console.log(`glyphs: ${chars.size}`);
